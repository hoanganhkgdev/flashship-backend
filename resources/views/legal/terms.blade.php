<p>Bằng cách sử dụng ứng dụng FlashShip, bạn đồng ý với các điều khoản sau.</p>

<h2>1. Dịch vụ</h2>
<p>FlashShip cung cấp nền tảng kết nối khách hàng với tài xế để thực hiện các dịch vụ: giao hàng, xe ôm, lái xe hộ, mua hộ và nạp tiền điện thoại.</p>

<h2>2. Tài khoản người dùng</h2>
<ul>
  <li>Bạn phải đủ 18 tuổi trở lên để sử dụng dịch vụ.</li>
  <li>Thông tin đăng ký phải chính xác và cập nhật.</li>
  <li>Bạn chịu trách nhiệm bảo mật mật khẩu tài khoản.</li>
  <li>Mỗi số điện thoại chỉ được đăng ký một tài khoản.</li>
</ul>

<h2>3. Đặt đơn và thanh toán</h2>
<ul>
  <li>Sau khi đặt đơn, hệ thống tự động tìm tài xế trong vòng 10 phút.</li>
  <li>Nếu không tìm được tài xế, đơn sẽ tự động huỷ.</li>
  <li>Phí dịch vụ được tính dựa trên khoảng cách và loại dịch vụ.</li>
  <li>Bạn có thể huỷ đơn khi đơn đang ở trạng thái "Chờ nhận".</li>
</ul>

<h2>4. Hành vi bị cấm</h2>
<ul>
  <li>Đặt đơn hàng giả mạo hoặc quấy rối tài xế.</li>
  <li>Sử dụng dịch vụ cho mục đích bất hợp pháp.</li>
  <li>Cung cấp thông tin sai lệch khi đăng ký.</li>
</ul>

<h2>5. Giới hạn trách nhiệm</h2>
<p>FlashShip là nền tảng kết nối. Chúng tôi không chịu trách nhiệm trực tiếp về thiệt hại phát sinh từ hành vi của tài xế, trừ trường hợp lỗi của hệ thống.</p>

<h2>6. Thay đổi điều khoản</h2>
<p>Chúng tôi có thể cập nhật điều khoản bất kỳ lúc nào. Tiếp tục sử dụng dịch vụ sau khi cập nhật đồng nghĩa với việc bạn chấp nhận điều khoản mới.</p>

