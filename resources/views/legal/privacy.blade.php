<h1>⚡ Chính sách Quyền riêng tư</h1>
<p class="updated">Cập nhật lần cuối: {{ date('d/m/Y') }}</p>

<p>FlashShip ("chúng tôi") cam kết bảo vệ thông tin cá nhân của bạn. Chính sách này mô tả cách chúng tôi thu thập, sử dụng và bảo vệ dữ liệu của bạn khi sử dụng ứng dụng FlashShip.</p>

<h2>1. Thông tin chúng tôi thu thập</h2>
<ul>
  <li><strong>Thông tin tài khoản:</strong> Họ tên, số điện thoại, email (tuỳ chọn), mật khẩu đã mã hóa.</li>
  <li><strong>Vị trí:</strong> Vị trí GPS của bạn khi đặt đơn để xác định địa chỉ giao hàng và tìm tài xế gần nhất. Chúng tôi chỉ truy cập vị trí khi ứng dụng đang được mở.</li>
  <li><strong>Thông tin đơn hàng:</strong> Địa chỉ lấy hàng, địa chỉ giao hàng, ghi chú đơn hàng.</li>
  <li><strong>Thiết bị:</strong> Token thiết bị để gửi thông báo đẩy (FCM).</li>
</ul>

<h2>2. Mục đích sử dụng</h2>
<ul>
  <li>Xử lý và theo dõi đơn hàng giao hàng, xe ôm, mua hộ.</li>
  <li>Tìm và kết nối với tài xế gần nhất.</li>
  <li>Gửi thông báo về trạng thái đơn hàng.</li>
  <li>Cải thiện chất lượng dịch vụ.</li>
</ul>

<h2>3. Chia sẻ thông tin</h2>
<p>Chúng tôi <strong>không bán</strong> thông tin cá nhân của bạn cho bên thứ ba. Thông tin chỉ được chia sẻ với:</p>
<ul>
  <li>Tài xế được phân công đơn hàng của bạn (tên, số điện thoại và địa chỉ giao hàng).</li>
  <li>Dịch vụ bản đồ Google Maps để hiển thị vị trí.</li>
  <li>Firebase (Google) để gửi thông báo đẩy.</li>
</ul>

<h2>4. Bảo mật dữ liệu</h2>
<p>Dữ liệu được mã hóa khi truyền tải (HTTPS). Mật khẩu được băm (bcrypt) và không thể đọc được. Chúng tôi áp dụng các biện pháp bảo mật tiêu chuẩn ngành.</p>

<h2>5. Lưu trữ dữ liệu</h2>
<p>Dữ liệu được lưu trữ trên máy chủ đặt tại Việt Nam. Khi bạn xóa tài khoản, toàn bộ dữ liệu cá nhân sẽ bị xóa vĩnh viễn trong vòng 30 ngày.</p>

<h2>6. Quyền của bạn</h2>
<ul>
  <li>Xem và chỉnh sửa thông tin cá nhân trong ứng dụng.</li>
  <li>Yêu cầu xóa tài khoản và toàn bộ dữ liệu.</li>
  <li>Từ chối nhận thông báo đẩy trong cài đặt thiết bị.</li>
</ul>

